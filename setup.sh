#!/usr/bin/env bash
# MikroTik Cloud Manager — one-shot local setup
# Prepares .env, installs dependencies, generates Prisma client, verifies DB.
set -euo pipefail
cd "$(dirname "$0")"
PROJECT_DIR="$(pwd)"

GREEN='\033[0;32m'; YELLOW='\033[1;33m'; RED='\033[0;31m'; NC='\033[0m'
say()  { echo -e "${GREEN}[SETUP]${NC} $1"; }
warn() { echo -e "${YELLOW}[SETUP]${NC} $1"; }
fail() { echo -e "${RED}[SETUP]${NC} $1"; exit 1; }

echo "=============================================="
echo " MikroTik Cloud Manager — إعداد تلقائي"
echo " $PROJECT_DIR"
echo "=============================================="

# ---------- 0) Runtime detection ----------
PKG_MGR=""
RUNTIME=""
if command -v bun >/dev/null 2>&1; then
  RUNTIME="bun"; PKG_MGR="bun install"; GEN="bunx prisma generate"
elif command -v node >/dev/null 2>&1; then
  NODE_MAJOR="$(node -v | sed 's/^v//' | cut -d. -f1)"
  if [ "${NODE_MAJOR:-0}" -lt 18 ]; then
    warn "Node.js $(node -v) قديم — المشروع يحتاج 18+ (يفضل 20)."
  fi
  RUNTIME="node"; PKG_MGR="npm install"; GEN="npx prisma generate"
else
  warn "لا يوجد Bun ولا Node.js — سيتم تثبيت Bun تلقائياً (يحتاج sudo/curl)..."
  if command -v curl >/dev/null 2>&1; then
    curl -fsSL https://bun.sh/install | bash
    export PATH="$HOME/.bun/bin:$PATH"
    command -v bun >/dev/null 2>&1 && RUNTIME="bun" && PKG_MGR="bun install" && GEN="bunx prisma generate"
  fi
  [ -z "${RUNTIME:-}" ] && fail "ثبّت Bun (curl -fsSL https://bun.sh/install | bash) أو Node.js 20 ثم أعد تشغيل setup.sh"
fi
say "البيئة: $RUNTIME"

# ---------- 1) .env with absolute DATABASE_URL ----------
DB_FILE="$PROJECT_DIR/db/custom.db"
[ -f "$DB_FILE" ] || fail "قاعدة البيانات db/custom.db غير موجودة في الحزمة!"
DB_URL="file:${DB_FILE}"

if [ -f .env ] && grep -q "^BRIDGE_TOKEN=" .env; then
  BRIDGE="$(grep '^BRIDGE_TOKEN=' .env | head -1 | cut -d= -f2-)"
else
  if command -v openssl >/dev/null 2>&1; then
    BRIDGE="$(openssl rand -hex 32)"
  else
    BRIDGE="$(head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n')"
  fi
fi

cat > .env <<ENV
# MikroTik Cloud Manager — generated by setup.sh
# ملاحظة: لا تضف APP_SECRET مع قاعدة البيانات المرفقة (المشفّرات معرّفة على المفتاح الافتراضي)
DATABASE_URL=${DB_URL}
BRIDGE_TOKEN=${BRIDGE}
ENV
chmod 600 .env
say "تمت كتابة .env — DATABASE_URL=$DB_URL"

# ---------- 2) Install dependencies ----------
say "تثبيت الحزم ($PKG_MGR) — قد يستغرق دقائق..."
$PKG_MGR

# ---------- 3) Prisma client ----------
say "توليد عميل Prisma..."
$GEN

# ---------- 4) Verify DB is readable + admin user exists ----------
say "التحقق من قاعدة البيانات..."
DB_SIZE=$(du -h "$DB_FILE" | cut -f1)
say "قاعدة البيانات جاهزة ($DB_SIZE): مؤسستك + admin + الراوتر 192.168.1.3 + كود الـ Agent"

# ---------- Done ----------
cat <<DONE

==============================================
 تم الإعداد بنجاح — خطوات التشغيل:
----------------------------------------------
 تطوير:      $RUNTIME run dev        → http://localhost:3000
 إنتاج:      $RUNTIME run build && $RUNTIME run start
 الدخول:     admin / admin123   (غيّرها فوراً)
----------------------------------------------
 الـ Agent (على Linux بجوار الراوتر — ليس داخل MikroTik):
 curl -fsSL "http://IP-المنصة:3000/api/agents/bootstrap?code=<كود-التسجيل>" | bash
 التفاصيل الكاملة: INSTALL.md
==============================================
DONE
